# -*- coding: utf-8 -*-
"""从 cap/practice_s2c_op*.bin 生成 Kotlin blob 常量 (保证逐字节一致)。
用法: python tools/gen_practice_kotlin.py > src/main/kotlin/pingu/packet/PracticeBlobs.kt
"""
import os

BASE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(BASE, "cap")

# 需要嵌入 Kotlin 的 blob: (Kotlin 常量名, 文件名) — 文件为含 2B opcode 的完整 payload
BLOBS = [
    ("EN_OP83", "practice_s2c_op83_8B_0.bin"),
    ("EN_OP113", "practice_s2c_op113_4B_0.bin"),
    ("EN_OP100_ROOM", "practice_s2c_op100_80B_0.bin"),
    ("EN_OP100_START", "practice_s2c_op100_79B_1.bin"),
    ("EN_OP108", "practice_s2c_op108_10B_0.bin"),
    ("EN_OP111", "practice_s2c_op111_3B_0.bin"),
    ("EN_OP112", "practice_s2c_op112_167B_0.bin"),
    ("EN_OP136", "practice_s2c_op136_180B_0.bin"),
    ("EN_OP172", "practice_s2c_op172_17B_0.bin"),
    ("EN_OP198_PRACTICE", "practice_s2c_op198_137B_0.bin"),
    ("EN_OP423_PRACTICE", "practice_s2c_op423_26B_0.bin"),
]


def fmt_kotlin_hex(b, per_line=16):
    lines = []
    for i in range(0, len(b), per_line):
        chunk = b[i:i + per_line]
        hexs = " ".join(f"{x:02x}" for x in chunk)
        lines.append(f"    {hexs}")
    return "\n".join(lines)


def main():
    print("package pingu.packet")
    print()
    print("import pingu.netty.toBA")
    print()
    print("// ============================================================")
    print("// Practice room (op 75) response-chain blobs.")
    print("// Extracted byte-exact from tst.pcap stream 4; generated by")
    print("// tools/gen_practice_kotlin.py. Do not hand-edit.")
    print("// ============================================================")
    for name, fname in BLOBS:
        with open(os.path.join(OUT, fname), "rb") as f:
            b = f.read()[2:]  # 去 2B opcode, 只嵌 body
        print(f"internal val {name} = \"\"\"")
        print(fmt_kotlin_hex(b))
        print("\"\"\".toBA()")
        print()


if __name__ == "__main__":
    main()
